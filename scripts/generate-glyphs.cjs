async function fetchOrGenerate(preset) {
  const filePath = path.join(GLYPHS_DIR, `${preset.id}.svg`);
  
  // Try DiceBear 10.x API first for crisp circle & clean output
  try {
    const url = `https://api.dicebear.com/10.x/glyphs/svg?seed=${encodeURIComponent(preset.seed)}&radius=50`;
    const res = await fetch(url);
    if (res.ok) {
      const svg = await res.text();
      fs.writeFileSync(filePath, svg, 'utf8');
      console.log(`[Generated via API] ${preset.label} -> ${preset.id}.svg`);
      return svg;
    }
  } catch (err) {
    console.warn(`API fetch failed for ${preset.label}, falling back to CLI...`);
  }

  // Fallback to CLI
  try {
    const tmpDir = path.join(GLYPHS_DIR, '_tmp');
    if (!fs.existsSync(tmpDir)) fs.mkdirSync(tmpDir, { recursive: true });
    execSync(`dicebear glyphs "${tmpDir}" --seed "${preset.seed}" --count 1`, { stdio: 'pipe' });
    const generated = fs.readdirSync(tmpDir).find(f => f.endsWith('.svg'));
    if (generated) {
      const svg = fs.readFileSync(path.join(tmpDir, generated), 'utf8');
      fs.writeFileSync(filePath, svg, 'utf8');
      fs.unlinkSync(path.join(tmpDir, generated));
      console.log(`[Generated via CLI] ${preset.label} -> ${preset.id}.svg`);
      return svg;
    }
  } catch (cliErr) {
    console.error(`CLI error generating ${preset.label}:`, cliErr.message);
  }

  return '';
}

async function main() {
  console.log(`Generating ${PRESETS.length} DiceBear Glyphs avatars...`);
  const results = [];

  for (const preset of PRESETS) {
    const svg = await fetchOrGenerate(preset);
    results.push({
      ...preset,
      svgContent: `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`,
    });
  }

  // Generate src/lib/dicebearGlyphsData.ts
  const tsContent = `// Auto-generated by scripts/generate-glyphs.cjs
// DiceBear Glyphs Avatar presets (CC BY 4.0 Matt Houser)
import type { AvatarOption } from './avatarCatalog';

export const GLYPHS_AVATARS: AvatarOption[] = ${JSON.stringify(
    results.map(r => ({
      id: r.id,
      label: r.label,
      category: 'glyphs',
      tier: r.tier,
      unlockRequirement: r.requirement,
      svgContent: r.svgContent,
      tags: r.tags,
      isFeatured: r.tier === 'starter' || r.tier === 'champion',
    })),
    null,
    2
  )};
`;

  const tsPath = path.resolve(__dirname, '../src/lib/dicebearGlyphsData.ts');
  fs.writeFileSync(tsPath, tsContent, 'utf8');
  console.log(`Wrote TypeScript presets to ${tsPath}`);
  console.log(`All ${PRESETS.length} glyph avatars successfully created!`);
}

main().catch(console.error);
